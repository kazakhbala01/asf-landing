/** Разделы с номером — причины; на карточке выводятся списком. */
export function numberedSections(a: Article) {
  return a.blocks.filter(
    (b): b is Extract<Block, { type: "h2" }> => b.type === "h2" && !!b.num
  );
}

export function tocItems(a: Article) {
  return a.blocks.filter((b): b is Extract<Block, { type: "h2" }> => b.type === "h2");
}

/** Время чтения: ~180 слов в минуту — средняя скорость для деловых текстов. */
export function readingMinutes(a: Article) {
  const words = JSON.stringify([a.intro, a.blocks, a.cta])
    .replace(/"(type|id|toc|num|target|tone)":"[^"]*"/g, "")
    .split(/\s+/).length;
  return Math.max(1, Math.round(words / 180));
}

export function formatDate(iso: string) {
  return new Date(iso).toLocaleDateString("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  });
}
