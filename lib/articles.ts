/**
 * Статьи блога. Одна статья = один объект в массиве `articles`:
 * карточка на главной, модальное окно и отдельная страница /stati/<slug>
 * строятся из этих данных автоматически, страница сама попадает в sitemap.
 *
 * В строках можно выделять жирным: **так**.
 */

export type Block =
  | { type: "p"; text: string }
  /** заголовок раздела; num — номер причины, toc — короткая подпись в оглавлении */
  | { type: "h2"; id: string; text: string; toc: string; num?: string }
  | { type: "h3"; text: string }
  | { type: "ul"; items: string[] }
  /** сетка-оглавление: пункт ведёт к разделу с id = target */
  | { type: "links"; items: { text: string; target: string }[] }
  | {
      type: "callout";
      tone: "ink" | "amber" | "check";
      title: string;
      text?: string[];
      items?: string[];
    }
  /** карточки с цифрой: разведения, параметры */
  | { type: "figures"; items: { value: string; label: string; text: string }[] }
  /** две колонки «одно / другое»; вторая — тёмная */
  | { type: "compare"; columns: [Column, Column] }
  | { type: "steps"; items: { title: string; text: string[]; items?: string[] }[] }
  | { type: "faq"; items: { q: string; a: string[] }[] };

type Column = { title: string; items: string[] };

export type Article = {
  slug: string;
  title: string;
  /** meta description и подзаголовок карточки */
  description: string;
  /** ISO-дата публикации */
  published: string;
  /** пронумерованные разделы: word — «Причина 01 / 08» в статье, label — «8 причин …» на карточке */
  numbered: { word: string; label: string };
  intro: string[];
  blocks: Block[];
  cta: { title: string; text: string[]; offer: string; message: string };
};

